using UnityEngine;

/// <summary>
/// 8방향 이웃 비트마스크 -> 타일 스프라이트 번호 대응표.
///
/// 손으로 찍은 스테이지 1의 Tilemap_Wall에서 역으로 학습했다.
/// (같은 이웃 배치에 실제로 쓰인 타일 중 최빈값. 42개 패턴, 적중률 90.4%)
/// 스테이지 1에 없던 배치는 학습된 패턴 중 가중 해밍 거리가 가장 가까운 것으로 메웠다.
/// 위/아래가 뚫렸는지가 외곽선 모양을 좌우하므로 N·S에 큰 가중치를,
/// 장식 수준인 대각선에는 작은 가중치를 줬다.
///
/// 이 표를 쓰면 코드로 찍은 맵도 기존 맵과 같은 아트 스타일로 나온다.
/// </summary>
public static class StageAutotile
{
	// 비트 순서: 0=N 1=NE 2=E 3=SE 4=S 5=SW 6=W 7=NW
	static readonly int[] dx = { 0, 1, 1, 1, 0, -1, -1, -1 };
	static readonly int[] dy = { 1, 1, 0, -1, -1, -1, 0, 1 };

	static readonly byte[] MaskToSprite =
	{
		11, 27, 11, 27, 20, 27, 20, 27, 11, 24, 11, 24, 20, 24, 20, 24,   //   0~15
		11,  0, 35,  0, 11,  0, 35,  0, 11,  0, 35,  0, 11,  0, 35,  0,   //  16~31
		11, 51, 11, 27, 20, 27, 20, 27, 11, 51, 11, 24, 20, 24, 20, 24,   //  32~47
		11, 19, 11, 43,  8, 43,  8, 43,  8, 16,  8, 43,  8, 43,  8, 43,   //  48~63
		20, 27, 20, 50, 20, 52, 20,  0, 20, 27, 20, 51, 20, 28, 20, 28,   //  64~79
		11, 19, 11, 19, 36, 37, 36, 32,  8, 16,  8, 16, 36, 37,  9, 10,   //  80~95
		20, 51, 20, 51, 20, 52, 20, 52, 20, 51, 20, 51, 20, 52, 20, 52,   //  96~111
		11, 19, 11, 19, 36, 32, 36, 32,  8, 16,  8, 16, 36, 10,  9, 10,   // 112~127
		11, 27, 11, 50, 20, 27, 20, 27, 11, 27, 11, 51, 20, 24, 20, 24,   // 128~143
		 8, 19, 35, 19, 11, 19, 35, 19, 11, 16, 35, 19, 11, 19, 35, 19,   // 144~159
		11, 51, 11, 51, 20, 27, 20, 27, 11, 51, 11, 51, 20, 24, 20, 24,   // 160~175
		 8, 19,  8, 19,  8, 43,  8, 43, 35, 16, 35, 16,  8, 43,  8, 43,   // 176~191
		20, 27, 20, 50, 36, 52, 36,  0, 20, 27, 20, 51, 36, 28, 36, 28,   // 192~207
		 8, 19,  8, 19,  9, 37, 36,  0, 35, 16, 35, 16,  9, 37, 36,  0,   // 208~223
		20, 51, 20, 51, 36, 28, 36, 28, 20, 51, 20, 51, 36, 28, 36, 28,   // 224~239
		 8, 19,  8, 19,  9, 10, 36,  0, 35, 16, 35, 16,  9, 10, 36,  0,   // 240~255
	};

	/// <summary>이웃이 벽인지 판정하는 함수를 받아 해당 칸의 스프라이트 번호를 돌려준다.</summary>
	public static int Resolve(int x, int y, System.Func<int, int, bool> isWall)
	{
		int mask = 0;
		for (int i = 0; i < 8; i++)
		{
			if (isWall(x + dx[i], y + dy[i])) mask |= 1 << i;
		}
		return MaskToSprite[mask];
	}
}
